/** A small dot + mono label — a diagnostic status readout ("● GRANTED"). */
@Composable
fun AmStatusPill(
    text: String,
    modifier: Modifier = Modifier,
    color: Color = LocalAlarmMeColors.current.primary,
) {
    Row(
        modifier = modifier,
        horizontalArrangement = Arrangement.spacedBy(7.dp),
        verticalAlignment = Alignment.CenterVertically
    ) {
        Box(
            modifier = Modifier
                .size(7.dp)
                .clip(CircleShape)
                .background(color)
        )
        Text(
            text = text,
            style = LocalAlarmMeTypography.current.labelSmall,
            color = color
        )
    }
}

@Preview(name = "Light Mode", showBackground = true)
@Preview(
    name = "Dark Mode",
    uiMode = android.content.res.Configuration.UI_MODE_NIGHT_YES
)
@Composable
private fun AmStatusPillPreview() {
    AlarmMeThemeProvider {
        AmStatusPill(text = "GRANTED")
    }
}
